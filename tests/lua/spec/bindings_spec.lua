local H = require("tests.lua.spec.helpers")
local Stub = require("tests.lua.spec.wow_stub")
local Loader = require("tests.lua.spec.loader")

describe("Bindings.xml and its globals", function()
  local xml
  setup(function() xml = H.readFile("addon/WoWForeverItalian/Bindings.xml") end)

  it("declares WFI_TOGGLE under header WFI, the hidden runOnUp WFI_REVEAL and the voice panel's two", function()
    local _, count = xml:gsub("<Binding%s", "")
    assert.are.equal(4, count)
    assert.is_truthy(xml:find('<Binding name="WFI_VOICE_PAUSE">WFI_VoicePause()</Binding>', 1, true))
    assert.is_truthy(xml:find('<Binding name="WFI_VOICE_REPLAY">WFI_VoiceReplay()</Binding>', 1, true))
    assert.is_nil(xml:find("SKIP", 1, true)) -- no next-line control
    assert.is_truthy(xml:find('<Binding name="WFI_TOGGLE" header="WFI">WFI_ToggleTranslation()</Binding>', 1, true))
    local attrs, body = xml:match('<Binding (name="WFI_REVEAL"[^>]*)>%s*(.-)%s*</Binding>')
    assert.is_truthy(attrs)
    assert.is_truthy(attrs:find('runOnUp="true"', 1, true))
    assert.is_truthy(attrs:find('hidden="true"', 1, true))
    assert.are.equal("WFI_RevealKey(keystate)", body)
  end)

  it("is not listed in the TOC (the client auto-loads it)", function()
    for _, f in ipairs(Loader.tocFiles(H.ADDON_DIR .. "/WoWForeverItalian.toc")) do
      assert.is_nil(f:find("Bindings", 1, true))
    end
  end)

  it("its body names a global that exists after load and toggles the master switch", function()
    Stub.install(H.ADDON_DIR .. "/WoWForeverItalian.toc")
    local WFI = Loader.load("WoWForeverItalian")
    Stub.fireAll("ADDON_LOADED", "WoWForeverItalian")
    local body = xml:match("<Binding%s[^>]*>%s*(.-)%s*</Binding>")
    local fnName = body:match("^([%w_]+)%(%)$")
    assert.is_truthy(fnName, "binding body must be a bare global call: " .. tostring(body))
    assert.is_function(_G[fnName])
    assert.is_true(WFI.Settings.get("enabled"))
    _G[fnName]()
    assert.is_false(WFI.Settings.get("enabled"))
    assert.is_false(WFI.State.enabled)
    _G[fnName]()
    assert.is_true(WFI.Settings.get("enabled"))
    assert.is_string(BINDING_HEADER_WFI); assert.is_true(#BINDING_HEADER_WFI > 0)
    assert.is_string(BINDING_NAME_WFI_TOGGLE); assert.is_true(#BINDING_NAME_WFI_TOGGLE > 0)
    assert.is_function(WFI_RevealKey)
    assert.is_truthy(BINDING_NAME_WFI_REVEAL:find("settings", 1, true))
    assert.is_function(WFI_VoicePause); assert.is_function(WFI_VoiceReplay)
    assert.is_string(BINDING_NAME_WFI_VOICE_PAUSE); assert.is_string(BINDING_NAME_WFI_VOICE_REPLAY)
  end)
end)
